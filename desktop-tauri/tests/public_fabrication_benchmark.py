"""Public, independently published STEP/PDF/BOM benchmark for the ACTUAL DS Estimate CAD EXE.

No geometry or reference drawings are generated by this test. It downloads
specific pinned upstream files and runs the compiled ds-cad-engine.exe. The
manual time ranges live separately in public_fabrication_projects.json and are
NOT supplied to the DS Estimate cutting planner.

A timeout/segfault is a test finding, never silently a PASS. An unreadable PDF
or missing STEP is reported. Downloaded models stay local to the CI runner;
artifact includes source hashes, extracted evidence, results and logs.
"""
import argparse, csv, hashlib, io, json, os, subprocess, sys, time, urllib.request
from pathlib import Path
from urllib.parse import quote

MAX_BYTES = 32 * 1024 * 1024
UA = 'DS-Estimate-public-fabrication-benchmark/1.0 (source attribution in report)'
ROOT = Path(__file__).resolve().parent
SOURCES = ROOT / 'public_fabrication_projects.json'

def download(repo, rev, path, output, max_size=MAX_BYTES):
    url=f'https://raw.githubusercontent.com/{repo}/{rev}/{quote(path, safe="/")}'
    request=urllib.request.Request(url, headers={'User-Agent':UA, 'Accept':'application/octet-stream'})
    with urllib.request.urlopen(request,timeout=75) as response:
        content_length=int(response.headers.get('Content-Length','0'))
        if content_length>max_size: raise ValueError(f'Oversized upstream file {content_length} bytes')
        data=response.read(max_size+1)
    if len(data)>max_size:raise ValueError(f'Upstream exceeds {max_size} bytes')
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_bytes(data)
    return {'upstream':url, 'sha256':hashlib.sha256(data).hexdigest(),'bytes':len(data)}

def read_pdf(path):
    import fitz
    with fitz.open(path) as doc:
        pages=len(doc)
        text='\n'.join(page.get_text('text') for page in doc)
        return pages, text

def safe_error(e):
    return f'{type(e).__name__}: {str(e)[:1500]}'

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--engine',type=Path,required=True)
    p.add_argument('--out',type=Path,default=Path('public_fabrication_output'))
    p.add_argument('--timeout',type=int,default=240)
    args=p.parse_args()
    args.out.mkdir(parents=True,exist_ok=True)
    cfg=json.loads(SOURCES.read_text(encoding='utf-8'))
    # DockHub is suspended by user request; retain its pinned source data for later.
    active_cases=[case for case in cfg['cases'] if case['id'] != 'dockhub']
    assert {case['id'] for case in active_cases} == {'portal-frame','stepgen-frame','earthpress'}, 'Unexpected active benchmark set'
    summaries=[]
    for case in active_cases:
        id=case['id']; start=time.monotonic();folder=args.out/id
        folder.mkdir(exist_ok=True)
        result={'id':id,'name':case['name'],'repo':case['repo'],'revision':case['sha'],
                'scope':case['source_scope'],'status':'PENDING','files':[],'pdf':[],
                'manualReference':case['manual'],'errors':[]}
        print('BEGIN_PUBLIC_PROJECT',id,case['repo'],flush=True)
        try:
            step=folder/Path(case['step']).name
            info=download(case['repo'],case['sha'],case['step'],step)
            if b'ISO-10303-21' not in step.read_bytes()[:300]: raise ValueError('Upstream STEP signature missing')
            result['files'].append({'kind':'STEP', 'path':case['step'], **info})
            for drawing in case['drawings']:
                try:
                    target=folder/Path(drawing).name
                    detail=download(case['repo'],case['sha'],drawing,target,max_size=4_000_000)
                    if not target.read_bytes().startswith(b'%PDF'): raise ValueError('PDF signature missing')
                    pages,text=read_pdf(target)
                    (folder/(target.stem+'.txt')).write_text(text[:200000],encoding='utf-8')
                    result['pdf'].append({'path':drawing,'pages':pages,'textChars':len(text),
                                          'sample':text[:700],**detail})
                except Exception as exc:
                    result['errors'].append('drawing '+drawing+': '+safe_error(exc))
            for kind, key in [('BOM','bom'),('instructions','build_plan')]:
                if not case.get(key):continue
                try:
                    path=case[key];target=folder/Path(path).name
                    info=download(case['repo'],case['sha'],path,target,max_size=600_000)
                    entry={'kind':kind,'path':path,**info}
                    if kind=='BOM':
                        decoded=target.read_text(encoding='utf-8-sig')
                        records=list(csv.DictReader(io.StringIO(decoded)))
                        entry['rows']=len(records)
                        entry['makeRows']=sum(1 for row in records if row.get('make_buy','').lower()=='make')
                    else:
                        entry['textChars']=len(target.read_text(encoding='utf-8'))
                    result['files'].append(entry)
                except Exception as exc:
                    result['errors'].append(kind+' '+str(case[key])+': '+safe_error(exc))
            if not result['pdf']: raise RuntimeError('No real source PDF could be read')
            result['status']='ENGINE_RUNNING'
            cmd=[str(args.engine.resolve()),str(step.resolve())]
            try:
                run=subprocess.run(cmd,capture_output=True,text=True,timeout=args.timeout)
                (folder/'engine_stderr.txt').write_text(run.stderr[-50000:],encoding='utf-8')
                if run.returncode!=0:
                    result['status']='ENGINE_FAILED'
                    result['engineExit']=run.returncode
                    result['errors'].append('CAD engine returned '+str(run.returncode)+': '+run.stderr[-800:])
                else:
                    data=json.loads(run.stdout)
                    if not data.get('solids') or not data.get('groups'):
                        raise ValueError('No solid/group inventory returned')
                    inventoryFile=folder/'ds_estimate_inventory.json'
                    inventoryFile.write_text(json.dumps(data,ensure_ascii=False),encoding='utf-8')
                    result['status']='ENGINE_OK'
                    result['engine']={'solids':data['count'],'groups':len(data['groups']),
                                      'massKgAssumed7850':data['totalMassKg'],
                                      'cutHints':sum(1 for s in data['solids'] if s.get('cuttingHint')),
                                      'matchingDiagnostics':data.get('matchingDiagnostics',{}),
                                      'limitations':data.get('limitations',[])}
            except subprocess.TimeoutExpired as exc:
                result['status']='ENGINE_TIMEOUT'
                result['errors'].append(f'Compiled DS Estimate engine exceeded {args.timeout} s')
                stderr=exc.stderr or b''
                if isinstance(stderr,bytes):
                    stderr=stderr.decode('utf-8','replace')
                (folder/'engine_stderr.txt').write_text(stderr[-50000:],encoding='utf-8')
                # Surface the last progress snapshots in the Actions log as well
                # as in artifacts. Without this, timeout hides the exact CAD
                # stage and the next iteration cannot locate the bottleneck.
                progress=[line for line in stderr.splitlines()
                          if 'DS-CAD-PROGRESS' in line or 'DS-CAD-PROFILE' in line]
                result['engineProgressTail']=progress[-8:]
                result['engineStderrTail']=stderr[-1500:]
                # The complete occurrence-to-group audit may exceed stderrTail.
                # Preserve the exact structured record, not a truncated fragment:
                # the 247/267 independent check still requires a finished inventory.
                audits=[line.split('[DS-CAD-GROUP-AUDIT]',1)[1].strip()
                        for line in stderr.splitlines() if '[DS-CAD-GROUP-AUDIT]' in line]
                if audits:
                    try:
                        audit=json.loads(audits[-1])
                        result['engineGroupAudit']=audit
                        (folder/'engine_group_audit.json').write_text(
                            json.dumps(audit,ensure_ascii=False,indent=2),encoding='utf-8')
                        print('ENGINE_TIMEOUT_GROUP_AUDIT',id,json.dumps({
                            'processedOccurrences':sum(len(v) for v in audit.get('groupOccurrences',{}).values()),
                            'auditedSameGroup':audit.get('auditedSameGroup'),
                            'auditedOccurrences':audit.get('auditedOccurrences'),
                            'groupCount':len(audit.get('groupOccurrences',{})),
                            'auditFile':'engine_group_audit.json'
                        },ensure_ascii=False),flush=True)
                    except (ValueError,TypeError) as audit_error:
                        result['engineGroupAuditError']=str(audit_error)
                print('ENGINE_TIMEOUT_PROGRESS',id,json.dumps({
                    'snapshots':progress[-8:],
                    'stderrTail':stderr[-1500:]},ensure_ascii=False),flush=True)
            except Exception as exc:
                result['status']='ENGINE_OUTPUT_INVALID'
                result['errors'].append(safe_error(exc))
        except Exception as exc:
            result['status']='INPUT_FAILED'
            result['errors'].append(safe_error(exc))
        result['seconds']=round(time.monotonic()-start,2)
        (folder/'manifest.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
        summaries.append(result)
        print('PUBLIC_CASE_RESULT',json.dumps({
            'id':id,'status':result['status'],'seconds':result['seconds'],
            'engine':result.get('engine'),'drawings':len(result['pdf']),
            'errors':result['errors'][:3]},ensure_ascii=False),flush=True)
    (args.out/'public_cases.json').write_text(json.dumps(summaries,ensure_ascii=False,indent=2),encoding='utf-8')
    print('PUBLIC_CASES_COMPLETED',len(summaries),'ENGINE_OK',sum(x['status']=='ENGINE_OK' for x in summaries),flush=True)
    if sum(x['status']=='ENGINE_OK' for x in summaries)!=len(summaries):
        sys.exit('PUBLIC_GATE_FAIL: Not all 3 active genuine public models analyzed by compiled DS Estimate CAD EXE. See artifacts; partial results are NOT a PASS.')
if __name__=='__main__':main()
